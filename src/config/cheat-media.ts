export function cheatScreenshotAt(index: number): CheatScreenshot {
  const list = MW4_CHEAT_SCREENSHOTS;
  return list[((index % list.length) + list.length) % list.length]!;
}

/** Stable blog hero image from slug (cycles the 11 shots). */
export function cheatScreenshotForSlug(slug: string): CheatScreenshot {
  let hash = 0;
  for (let i = 0; i < slug.length; i++) {
    hash = (hash * 31 + slug.charCodeAt(i)) | 0;
  }
  return cheatScreenshotAt(Math.abs(hash));
}

export function cheatScreenshotSrcForSlug(slug: string): string {
  return cheatScreenshotForSlug(slug).src;
}

/** Product hero / gallery slides (same shape as ProductSlide in products.ts). */
export function cheatScreenshotSlides(
  indices?: number[],
): Pick<CheatScreenshot, 'src' | 'alt' | 'caption' | 'captionDesc'>[] {
  const picks =
    indices?.length ?
      indices.map((i) => cheatScreenshotAt(i))
    : MW4_CHEAT_SCREENSHOTS;

  const seen = new Set<string>();
  const out: Pick<CheatScreenshot, 'src' | 'alt' | 'caption' | 'captionDesc'>[] = [];
  for (const shot of picks) {
    if (seen.has(shot.src)) continue;
    seen.add(shot.src);
    out.push({
      src: shot.src,
      alt: shot.alt,
      caption: shot.caption,
      captionDesc: shot.captionDesc,
    });
  }
  return out;
}

